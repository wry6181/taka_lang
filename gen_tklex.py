#!/usr/bin/env python3
# Regenerates the GENERATED block at the end of self_lex.tk from
# lexer.h (kind ordinals) + lexer.c (keyword table).
# Usage (from repo root): python3 gen_tklex.py
import re

h = open('lexer.h').read()
c = open('lexer.c').read()
enum_body = h.split('typedef enum {')[1].split('} TokenKind')[0]
names = []
for line in enum_body.split('\n'):
    line = line.split('//')[0].strip().rstrip(',')
    m = re.match(r'(TOKEN_[A-Z0-9_]+)', line)
    if m:
        names.append(m.group(1))
ords = {n: i for i, n in enumerate(names)}
kws = re.findall(r'\{"([^"]*)",\s*(TOKEN_[A-Z0-9_]+)\}', c)

out = []
out.append("// GENERATED by gen_tklex.py from lexer.h + lexer.c -- do not hand-edit.")
out.append("// Token-kind ordinals (must match C TokenKind).")
for n in names:
    out.append(f"i32 K_{n[6:]} = {ords[n]};")
out.append("")
out.append("fn tk_lookup_kw(sview w) -> i32 {")
for text, kind in kws:
    out.append(f'    if (str_eq(w, tk_sview("{text}", {len(text)}))) {{ return K_{kind[6:]}; }}')
out.append("    return K_IDENT;")
out.append("}")

src = open('self_lex.tk').read().split('\n')
cut = next(i for i, l in enumerate(src) if l.startswith('// GENERATED'))
src = src[:cut]
open('self_lex.tk', 'w').write('\n'.join(src) + '\n' + '\n'.join(out) + '\n')
print(f"self_lex.tk regenerated: {len(names)} kinds, {len(kws)} keywords")
