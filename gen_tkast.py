#!/usr/bin/env python3
# Generates taka kind constants for ast.h enums + token kind-name table.
# Usage: python3 gen_tkast.py   (writes /tmp/tkast_gen.tk)
import re

h = open('ast.h').read()
lx = open('lexer.c').read()


def enum_names(body):
    names = []
    for line in body.split('\n'):
        line = line.split('//')[0]
        for m in re.finditer(r'(TK_[A-Z0-9_]+)', line):
            names.append(m.group(1))
    return names


def grab(src, ename):
    end = src.index('} ' + ename + ';')
    start = src.rindex('typedef enum {', 0, end)
    return src[start:end]


out = []
out.append("// GENERATED by gen_tkast.py from ast.h + lexer.c -- do not hand-edit.")
for ename in [
    'TkExprKind', 'TkStmtKind', 'TkPatKind', 'TkTypeKind', 'TkItemKind',
]:
    body = grab(h, ename)
    for i, n in enumerate(enum_names(body)):
        assert n.startswith('TK_'), n
        out.append(f"i32 X_{n[3:]} = {i};")
    out.append("")

# token kind -> token_name string (for parse_error parity)
cases = re.findall(r'case (TOKEN_[A-Z0-9_]+):\s*return "((?:[^"\\]|\\.)*)";', lx)
out.append("fn tk_kind_name(i32 k) -> sview {")
seen = set()
for tok, name in cases:
    if tok in seen:
        continue
    seen.add(tok)
    esc = name.replace('\\', '\\\\').replace('"', '\\"')
    out.append(f'    if (k == K_{tok[6:]}) {{ return tk_sview("{esc}", {len(name)}); }}')
out.append('    return tk_sview("?", 1);')
out.append("}")
open('/tmp/tkast_gen.tk', 'w').write('\n'.join(out) + '\n')
print(f"kinds ok")
